import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { format, resolveConfig } from 'prettier';

import {
  GAME_ICON_SPRITE_DIR,
  GAME_ICON_SPRITE_URL_FILE,
  buildGameIconSprite,
  buildGameIcons,
  gameIconSpriteName,
} from './game-icons';

// Bundles the game icons the app uses into one static SVG sprite, so the browser never fetches
// them from the Iconify API and their data stays out of the JS bundle.
// Run after adding or renaming a game icon: npm run icons
const icons = buildGameIcons();
const sprite = buildGameIconSprite(icons);
const name = gameIconSpriteName(sprite);

mkdirSync(GAME_ICON_SPRITE_DIR, { recursive: true });
for (const old of readdirSync(GAME_ICON_SPRITE_DIR)) {
  if (/^game-[0-9a-f]+\.svg$/.test(old) && old !== name)
    rmSync(path.join(GAME_ICON_SPRITE_DIR, old));
}
writeFileSync(path.join(GAME_ICON_SPRITE_DIR, name), sprite);
const source = [
  '// Generated by `npm run icons`. Do not edit.',
  `export const GAME_ICON_SPRITE = '/icons/${name}';`,
  `export const GAME_ICON_NAMES: ReadonlySet<string> = new Set(${JSON.stringify(Object.keys(icons))});`,
  '',
].join('\n');
// Formatted like the rest of the code, so the commit hook leaves it untouched
const options = await resolveConfig(GAME_ICON_SPRITE_URL_FILE);
writeFileSync(
  GAME_ICON_SPRITE_URL_FILE,
  await format(source, { ...options, filepath: GAME_ICON_SPRITE_URL_FILE }),
);
console.log(
  `✨ ${Object.keys(icons).length} game icons written to ${GAME_ICON_SPRITE_DIR}/${name}`,
);
