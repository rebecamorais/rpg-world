import { writeFileSync } from 'node:fs';

import {
  GAME_ICON_NAMES_FILE,
  GAME_ICON_SPRITE_FILE,
  buildGameIconSprite,
  buildGameIcons,
} from './game-icons';
import { writeFormatted } from './write-formatted';

// Bundles the game icons the app uses into one SVG sprite, so the browser never fetches them from
// the Iconify API and their data stays out of the JS bundle.
// Run after adding or renaming a game icon: npm run icons
const icons = buildGameIcons();
const names = Object.keys(icons);

writeFileSync(GAME_ICON_SPRITE_FILE, buildGameIconSprite(icons));
await writeFormatted(
  GAME_ICON_NAMES_FILE,
  [
    '// Generated by `npm run icons`. Do not edit.',
    `export const GAME_ICON_NAMES: ReadonlySet<string> = new Set(${JSON.stringify(names)});`,
  ].join('\n'),
);
console.log(`✨ ${names.length} game icons written to ${GAME_ICON_SPRITE_FILE}`);
